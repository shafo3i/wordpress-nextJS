"use client"

import Link from "next/link"
import { usePathname } from "next/navigation"
import { getActiveNavigationId } from "./navigation"
import styles from "./header.module.css"
import { useEffect, useId, useRef, useState, type CSSProperties } from "react"
import { Search, Home, Menu, X } from "lucide-react"
import type { FrontEndThemeContext } from "@/lib/site-theme"
import {
  formatDate,
  getPostUrl,
  localizePath,
  t,
} from "@/components/site/utils"
import { SocialLinks } from "@/components/site/social-links"

type CssVars = CSSProperties

const RULES: Record<string, string> = {
  double: "4px double var(--theme-header-border)",
  solid: "1px solid var(--theme-header-border)",
  none: "none",
}

/** Colours come from the --theme-* variables generated by buildThemeCss, never from literals. */
export function SiteHeader({ theme }: { theme: FrontEndThemeContext }) {
  const mods = theme.mods || {}
  const pathname = usePathname() || "/"
  const navigationId = useId()
  const menuButton = useRef<HTMLButtonElement>(null)
  const [mobileMenu, setMobileMenu] = useState({ path: pathname, open: false })
  const mobileOpen = mobileMenu.path === pathname && mobileMenu.open
  const closeMobileMenu = () => setMobileMenu({ path: pathname, open: false })
  useEffect(() => {
    if (!mobileOpen) return
    const keyboard = (event: KeyboardEvent) => {
      if (event.key === "Escape") {
        setMobileMenu({ path: pathname, open: false })
        menuButton.current?.focus()
      }
    }
    const desktop = window.matchMedia("(min-width: 768px)")
    const resize = () => {
      if (desktop.matches) setMobileMenu({ path: pathname, open: false })
    }
    document.addEventListener("keydown", keyboard)
    desktop.addEventListener("change", resize)
    return () => {
      document.removeEventListener("keydown", keyboard)
      desktop.removeEventListener("change", resize)
    }
  }, [mobileOpen, pathname])
  const activeId = getActiveNavigationId(theme.primaryNav || [], pathname)
  const headerRef = useRef<HTMLElement>(null)
  const navRef = useRef<HTMLElement>(null)
  const [navOffset, setNavOffset] = useState(0)

  const headerLayout = mods.headerLayout || theme.headerLayout || "classic"
  const stickyNavigation =
    mods.stickyHeader !== false && Boolean(theme.primaryNav?.length)
  useEffect(() => {
    const header = headerRef.current
    const nav = navRef.current
    if (!header || !nav || !stickyNavigation) return
    const measure = () =>
      setNavOffset(
        Math.max(
          0,
          nav.getBoundingClientRect().top - header.getBoundingClientRect().top
        )
      )
    const observer = new ResizeObserver(measure)
    observer.observe(header)
    observer.observe(nav)
    measure()
    return () => observer.disconnect()
  }, [headerLayout, stickyNavigation, theme.primaryNav])
  const borderBottom = RULES[mods.headerBorderStyle || "double"] ?? RULES.double
  const homeHref = localizePath("/", theme.locale, theme.defaultLocale)

  const headerStyle: CssVars = {
    backgroundColor: "var(--theme-header-bg)",
    color: "var(--theme-header-text)",
    borderBottom,
    top: stickyNavigation
      ? `calc(var(--site-admin-bar-height, 0px) - ${navOffset}px)`
      : undefined,
  }
  const navStyle: CssVars = {
    backgroundColor: "var(--theme-nav-bg)",
    color: "var(--theme-nav-link)",
    borderTop: "1px solid var(--theme-header-border)",
  }
  const titleStyle = (fallbackWeight: string): CssVars => ({
    color: "var(--theme-header-text)",
    textTransform: mods.headingTransform || "none",
    fontWeight: mods.headingFontWeight || fallbackWeight,
  })
  const taglineStyle: CssVars = { color: "var(--theme-muted)" }
  const stickyClass = stickyNavigation ? "sticky z-40" : ""

  const renderLogo = (fallbackWidth: number, className = "") =>
    mods.logoUrl ? (
      <img
        src={mods.logoUrl}
        alt={theme.siteTitle}
        style={{ width: `${mods.logoWidth || fallbackWidth}px` }}
        className={[styles.logo, className].join(" ")}
      />
    ) : null

  const showSocialsInNav =
    mods.showTopBar === false && mods.showSocialIconsInHeader !== false

  const renderSearchIcon = () =>
    (mods.showSearchInNav !== false || showSocialsInNav) && (
      <div className={styles.utility}>
        {showSocialsInNav && (
          <div className={styles.navSocials}>
            <SocialLinks mods={mods} />
          </div>
        )}
        {mods.showSearchInNav !== false && (
          <Link
            href={localizePath("/search", theme.locale, theme.defaultLocale)}
            aria-label={t("site.search.label", theme, "")}
            className="inline-flex items-center justify-center p-2"
          >
            <Search className="size-4" aria-hidden="true" />
          </Link>
        )}
      </div>
    )
  // Top Bar Ticker & Utility
  const renderTopBar = () => {
    if (mods.showTopBar === false) return null

    const showTicker = theme.activePlugins?.includes("breaking-news")
    const latestBreaking = theme.breakingPosts?.[0]
    const tickerText =
      latestBreaking?.title ||
      (mods.topBarTickerText
        ? theme.dict?.[mods.topBarTickerText] || mods.topBarTickerText
        : null)
    const tickerUrl = latestBreaking
      ? getPostUrl(latestBreaking.slug, theme)
      : undefined

    return (
      <div
        style={{
          backgroundColor: "var(--theme-topbar-bg)",
          color: "var(--theme-topbar-text)",
        }}
        className="border-b border-black/10 px-4 py-1.5 text-xs sm:px-6"
      >
        <div className="theme-container mx-auto flex flex-wrap items-center justify-between gap-y-2">
          {showTicker && tickerText ? (
            <div className="flex items-center gap-2 overflow-hidden text-ellipsis whitespace-nowrap">
              <span
                style={{
                  backgroundColor: "var(--theme-topbar-ticker-bg)",
                  color: "var(--theme-topbar-ticker-text)",
                }}
                className="flex-shrink-0 animate-pulse rounded px-1.5 py-0.5 text-[0.625rem] font-bold tracking-wider uppercase"
              >
                {t("site.breaking", theme, "Breaking")}
              </span>
              {tickerUrl ? (
                <Link
                  href={tickerUrl}
                  className="max-w-xl truncate text-xs font-medium hover:underline"
                >
                  {tickerText}
                </Link>
              ) : (
                <span className="max-w-xl truncate text-xs font-medium">
                  {tickerText}
                </span>
              )}
            </div>
          ) : (
            <span />
          )}
          <div
            className={["flex items-center gap-3", styles.topbarUtilities].join(
              " "
            )}
          >
            {mods.showSocialIconsInHeader !== false && (
              <SocialLinks mods={mods} />
            )}
            {mods.showDateInHeader !== false && (
              <span className="hidden flex-shrink-0 font-mono text-[0.6875rem] opacity-75 sm:inline">
                {formatDate(new Date(), theme.locale, theme.timeZone)}
              </span>
            )}
            {theme.languages && theme.languages.length > 1 && (
              <div className="flex items-center gap-1.5 border-s border-current/20 ps-3 text-[0.6875rem] font-medium">
                {theme.languages.map((lang, idx) => (
                  <span
                    key={lang.code}
                    className="inline-flex items-center gap-1.5"
                  >
                    {idx > 0 && <span className="opacity-40">|</span>}
                    <Link
                      href={lang.url}
                      className={`transition-opacity hover:underline ${
                        lang.isActive
                          ? "font-bold underline"
                          : "opacity-80 hover:opacity-100"
                      }`}
                      title={lang.name}
                    >
                      {lang.nativeName || lang.name}
                    </Link>
                  </span>
                ))}
              </div>
            )}
          </div>
        </div>
      </div>
    )
  }

  const justify =
    mods.navAlignment === "center"
      ? "center"
      : mods.navAlignment === "right"
        ? "flex-end"
        : mods.navAlignment === "between"
          ? "space-between"
          : "flex-start"
  const hasBrand = Boolean(
    mods.logoUrl ||
    mods.showSiteTitle !== false ||
    (mods.showTagline !== false && theme.siteTagline)
  )
  return (
    <header
      dir={theme.direction}
      ref={headerRef}
      data-layout={headerLayout}
      style={headerStyle}
      className={[styles.header, stickyClass].join(" ")}
    >
      {renderTopBar()}
      {hasBrand && (
        <div className={["theme-container mx-auto", styles.masthead].join(" ")}>
          <div className={styles.brand}>
            {mods.logoUrl ? (
              <Link href={homeHref}>
                {renderLogo(headerLayout === "minimal" ? 140 : 200)}
              </Link>
            ) : (
              mods.showSiteTitle !== false && (
                <Link
                  href={homeHref}
                  style={titleStyle(headerLayout === "minimal" ? "700" : "900")}
                  className={["theme-site-title", styles.nameplate].join(" ")}
                >
                  {theme.siteTitle}
                </Link>
              )
            )}
            {mods.showTagline !== false && theme.siteTagline && (
              <p style={taglineStyle} className={styles.tagline}>
                {theme.siteTagline}
              </p>
            )}
          </div>
        </div>
      )}
      {theme.primaryNav?.length > 0 && (
        <nav
          ref={navRef}
          data-site-navigation
          style={navStyle}
          className={styles.navigation}
          aria-label={t("site.primary_navigation", theme)}
        >
          <div
            className={["theme-container mx-auto", styles.navInner].join(" ")}
          >
            <button
              ref={menuButton}
              type="button"
              className={styles.menuToggle}
              aria-controls={navigationId}
              aria-expanded={mobileOpen}
              aria-label={t(
                mobileOpen ? "site.navigation.close" : "site.navigation.open",
                theme,
                ""
              )}
              onClick={() =>
                setMobileMenu({ path: pathname, open: !mobileOpen })
              }
            >
              {mobileOpen ? (
                <X aria-hidden="true" size={20} />
              ) : (
                <Menu aria-hidden="true" size={20} />
              )}
              <span>{t("site.navigation.menu", theme, "")}</span>
            </button>
            <div
              id={navigationId}
              data-mobile-open={mobileOpen ? "true" : "false"}
              className={styles.links}
              data-style={mods.navStyle || "classic-text"}
              style={{
                justifyContent:
                  justify === "space-between" ? justify : `safe ${justify}`,
              }}
            >
              {theme.primaryNav.map((item) => (
                <Link
                  key={item.id}
                  onClick={closeMobileMenu}
                  href={item.url}
                  target={item.target || undefined}
                  rel={
                    item.target === "_blank" ? "noopener noreferrer" : undefined
                  }
                  aria-current={item.id === activeId ? "page" : undefined}
                  className={["theme-nav-link", styles.link].join(" ")}
                  style={{
                    textTransform: mods.navUppercase ? "uppercase" : "none",
                  }}
                >
                  {item.url === homeHref && (
                    <Home size={12} aria-hidden="true" />
                  )}
                  {item.title}
                </Link>
              ))}
              {showSocialsInNav && (
                <div className={styles.mobileSocials}>
                  <SocialLinks mods={mods} />
                </div>
              )}
            </div>
            {renderSearchIcon()}
          </div>
        </nav>
      )}
    </header>
  )
}
