import { beforeEach, describe, expect, it, vi } from "vitest"
vi.mock("server-only", () => ({}))
vi.mock("@/db", () => ({ db: {} }))
const mocks = vi.hoisted(() => ({ config: vi.fn(), send: vi.fn(), close: vi.fn() }))
vi.mock("@/services/media-storage.service", () => ({ getS3StorageConfig: mocks.config }))
vi.mock("@/lib/s3-storage", () => ({ createS3StorageClient: async () => ({ client: { send: mocks.send }, close: mocks.close }) }))
import { openS3MediaUpload, deleteS3MediaObjects } from "@/services/media-object-storage.service"
const config = { enabled: true, endpoint: "https://s3.eu-central-1.wasabisys.com", region: "eu-central-1", bucket: "news-media", prefix: "media", publicBaseUrl: "https://media.example.test", accessKeyId: "private", secretAccessKey: "private" }
beforeEach(() => { vi.clearAllMocks(); mocks.config.mockResolvedValue(config); mocks.send.mockResolvedValue({}) })
describe("object storage ownership and writes", () => {
  it("writes generated keys with safe content metadata and tracks cleanup without credentials", async () => {
    const upload = await openS3MediaUpload("2026/11", "image.jpg")
    await upload.write("image.jpg", Buffer.from("image"), "image/jpeg")
    await upload.write("document.txt", Buffer.from("text"), "text/plain")
    expect(mocks.send.mock.calls[0][0].input).toMatchObject({ Bucket: "news-media", ContentType: "image/jpeg", ContentDisposition: "inline", ContentLength: 5 })
    expect(mocks.send.mock.calls[0][0].input).not.toHaveProperty("ACL")
    expect(mocks.send.mock.calls[1][0].input.ContentDisposition).toBe("attachment")
    expect(upload.identity.key).toMatch(/^media\/pressforge\/[\da-f-]{36}\/2026\/11\/image.jpg$/)
    expect(upload.identity.objects).toHaveLength(2)
    expect(JSON.stringify(upload.identity)).not.toContain("private")
    await upload.cleanup()
    expect(mocks.send).toHaveBeenCalledTimes(4)
    upload.close()
    expect(mocks.close).toHaveBeenCalled()
  })
  it("rejects disabled destinations and traversal before object writes", async () => {
    mocks.config.mockResolvedValueOnce({ ...config, enabled: false })
    await expect(openS3MediaUpload("2026/11", "image.jpg")).rejects.toThrow("unavailable")
    const upload = await openS3MediaUpload("2026/11", "image.jpg")
    await expect(upload.write("../other.jpg", Buffer.from("x"), "image/jpeg")).rejects.toThrow("unsafe_path")
    expect(mocks.send).not.toHaveBeenCalled()
  })
  it("deletes only owned objects and refuses mismatched buckets, endpoints or unowned keys", async () => {
    const upload = await openS3MediaUpload("2026/11", "image.jpg")
    await upload.write("image.jpg", Buffer.from("image"), "image/jpeg")
    const url = upload.url("image.jpg")
    mocks.send.mockClear()
    await deleteS3MediaObjects(upload.identity, url)
    expect(mocks.send.mock.calls[0][0].input).toEqual({ Bucket: "news-media", Key: upload.identity.key })
    mocks.send.mockClear()
    for (const storage of [{ ...upload.identity, objects: ["another/object.jpg"] }, { ...upload.identity, folder: "../escape" }, { ...upload.identity, bucket: "another-bucket" }, { ...upload.identity, endpoint: "https://other.example.test" }]) await expect(deleteS3MediaObjects(storage, url)).rejects.toThrow()
    expect(mocks.send).not.toHaveBeenCalled()
  })
})
